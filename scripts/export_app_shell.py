#!/usr/bin/env python3
"""Write the study app's shell (CSS, HTML skeleton, page script) for the Chrome extension.

Usage:
  py -3 scripts/export_app_shell.py [--out PATH]

`extensions/notebooklm-study-app/popup.js` renders the same single-file app as
`scripts/build_study_app.py`, so the extension ships that builder's own CSS, HTML and page script
instead of a copy. Re-run this after changing any of the three constants in `build_study_app.py`;
`tests/test_extension.py` fails when the file on disk is stale.
"""
import argparse, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_study_app as app  # noqa: E402  (scripts/ is a flat folder, not a package)

DEFAULT_OUT = ROOT / "extensions" / "notebooklm-study-app" / "app-shell.js"


def shell_text():
    """The generated file's exact content: one JSON object, no timestamp, so a diff is meaningful."""
    shell = {"css": app.CSS, "html": app.HTML, "js": app.JS}
    return "/* Generated by scripts/export_app_shell.py from scripts/build_study_app.py. Do not edit. */\n" \
           "globalThis.STUDY_SHELL = " + json.dumps(shell, ensure_ascii=False) + ";\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description="Write the extension's copy of the study app shell.")
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    a = ap.parse_args(argv)
    dest = Path(a.out)
    dest.parent.mkdir(parents=True, exist_ok=True)
    with dest.open("w", encoding="utf-8", newline="\n") as f:
        f.write(shell_text())
    print(f"wrote {dest} ({dest.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
